// Offline only: node node_modules/vite-node/vite-node.mjs --config vitest.config.ts scripts/qa/measure-bone-bvh-padding.ts
import { writeFileSync, readFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { Group, Matrix4, SkinnedMesh, Vector3 } from 'three';
import { loadRig } from '../../tests/helpers/alienPose';
import { PlayerAnimationController, ANIM_FLOAT } from '../../client/src/player/playerAnimationController';
import { applyFloatArmTilt } from '../../client/src/player/playerAimPose';

const root=new Group(),animation=new PlayerAnimationController(),durations=new Map<string,number>();
const hashes:string[]=[];
for(const asset of ['Alien','Alien_Helmet']) {
  const {root:rig,animations}=await loadRig(asset);root.add(rig);animation.registerRig(rig,animations);
  for(const clip of animations) durations.set(clip.name,Math.max(durations.get(clip.name)??0,clip.duration));
  hashes.push(`${asset}.glb ${createHash('sha256').update(readFileSync(new URL(`../../client/public/models/${asset}.glb`,import.meta.url))).digest('hex')}`);
}
const meshes:SkinnedMesh[]=[];root.traverse(n=>{if(n instanceof SkinnedMesh) meshes.push(n);});
const groups=meshes.map(mesh=>{
  const owners=new Map<number,Set<number>>(),{skinIndex,skinWeight}=mesh.geometry.attributes;
  const indices=mesh.geometry.index!;
  for(let t=0;t<indices.count;t+=3) {
    const bones=new Set<number>();
    for(let k=0;k<3;k++) for(let slot=0;slot<4;slot++) if(skinWeight.getComponent(indices.getX(t+k),slot)>=.1) bones.add(skinIndex.getComponent(indices.getX(t+k),slot));
    for(const bone of bones) {
      if(!owners.has(bone)) owners.set(bone,new Set());
      for(let k=0;k<3;k++) owners.get(bone)!.add(indices.getX(t+k));
    }
  }
  return {mesh,owners,positions:new Float64Array(mesh.geometry.attributes.position.count*3)};
});
const pads:Record<string,number>={},point=new Vector3(),bind=new Vector3(),inverse=new Matrix4();
for(const [clip,duration] of durations) {
  animation.snapToAnimation(clip);
  for(let frame=0;frame<=Math.ceil(duration*30);frame++) {
    animation.tickMixers(frame===0?0:1/30);
    if(clip===ANIM_FLOAT) {animation.restoreFloatRightArmPose();applyFloatArmTilt(animation.getRigs());}
    root.updateWorldMatrix(true,true);root.updateMatrixWorld(true);
    for(const {mesh,owners,positions} of groups) {
      for(let v=0;v<mesh.geometry.attributes.position.count;v++) mesh.getVertexPosition(v,point).applyMatrix4(mesh.matrixWorld).toArray(positions,v*3);
      for(const [bone,vertices] of owners) {
        inverse.multiplyMatrices(mesh.skeleton.bones[bone].matrixWorld,mesh.skeleton.boneInverses[bone]).multiply(mesh.bindMatrix).invert();
        const name=mesh.skeleton.bones[bone].name;let maximum=pads[name]??0;
        for(const v of vertices) {
          point.fromArray(positions,v*3).applyMatrix4(inverse);bind.fromBufferAttribute(mesh.geometry.attributes.position,v);
          maximum=Math.max(maximum,Math.abs(point.x-bind.x),Math.abs(point.y-bind.y),Math.abs(point.z-bind.z));
        }
        pads[name]=maximum;
      }
    }
  }
  console.log(`Sampled ${clip}`);
}
const padded=Object.fromEntries(Object.entries(pads).sort(([a],[b])=>a.localeCompare(b)).map(([bone,pad])=>[bone,Math.ceil((pad*1.1+1e-5)*1e6)/1e6]));
if(!Object.values(padded).every(n=>Number.isFinite(n)&&n>0)) throw Error('Invalid displacement pad');
writeFileSync(new URL('../../client/src/player/boneBvhPadding.ts',import.meta.url),
  `// Generated by scripts/qa/measure-bone-bvh-padding.ts; all ${durations.size} clips at 30 Hz, FLOATING arm overlay.\n`+
  `// Max component displacement in geometry bind space, plus 10% and 1e-5.\n`+
  `// Offline diagnostic samples; production uses proven load-time rotation bounds.\n`+
  hashes.map(hash=>`// ${hash}\n`).join('')+
  `export const BONE_BVH_PADDING: Readonly<Record<string,number>> = ${JSON.stringify(padded,null,2)};\n`);
